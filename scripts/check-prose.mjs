#!/usr/bin/env node
// House prose style: no em/en dashes in prose, and no stock AI phrasing.
// Fails on typography; reports stock phrasing as a warning so a legitimate
// technical use ("robust against malformed input") is not blocked.
import { execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'

const EXT = /\.(md|ts|js|mjs|cjs|sh|py|yml|yaml|json|txt)$/
const ALLOWED = [
  /^\.github\/scripts\/herald-summary\.cjs$/, // mirrors the required-check names
  /^tests\/unit\/scripts\/herald-summary\.test\.ts$/, // fixtures mirror those names
  /^docs\/release-notes\.md$/, // generated from CHANGELOG
  /(^|\/)CHANGELOG\.md$/, // generated by semantic-release and changesets
  /package-lock\.json$/, // generated dependency tree
]

// A dash may stay only on a line that is a required-check identity: renaming
// one drops the branch-protection requirement. Everything else in a workflow
// is prose (step names, comments, run blocks) and follows the normal rule.
const WORKFLOW = /^\.github\/workflows\//
const IDENTITY = [
  /^\s*(-\s+)?name:\s/, // workflow, job and step names
  /^\s*-\s+(Society|The [A-Z]\w*)[^\u2014]*\u2014/, // herald.yml's watched-workflow list
]

const IGNORE = 'prose-lint-ignore'

// Keep in sync with the table in docs/conventions/WRITING_STYLE.md.
const STOCK = [
  'delve', 'tapestry', 'realm', 'testament to', 'game-changer', 'paradigm shift',
  'best-in-class', 'cutting-edge', 'state-of-the-art', 'ever-evolving',
  "in today's", 'it is worth noting', "it's worth noting", "let's dive",
  'deep dive', 'at the end of the day', 'when it comes to', 'plethora',
  'myriad', 'synergy', 'holistic', 'seamless', 'seamlessly', 'leverage',
  'unlock', 'elevate', 'empower', 'streamline', 'robust', 'comprehensive',
  'crucial', 'underscore', 'foster', 'embark',
].map((phrase) => [phrase, new RegExp(`\\b${phrase.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`)])

/** Quoted words and inline code name things; they are not prose claims. */
function proseOnly(line) {
  return line.replace(/`[^`]*`/g, '').replace(/"[^"]*"/g, '')
}

const files = execFileSync('git', ['ls-files'], { encoding: 'utf8' })
  .split('\n')
  .filter((file) => file && EXT.test(file) && !ALLOWED.some((re) => re.test(file)))

const violations = []
const warnings = []

for (const file of files) {
  let text
  try {
    text = readFileSync(file, 'utf8')
  } catch {
    continue
  }
  const isWorkflow = WORKFLOW.test(file)
  text.split('\n').forEach((line, index) => {
    if (line.includes(IGNORE)) return
    const identity = isWorkflow && IDENTITY.some((re) => re.test(line))
    const prose = proseOnly(line)
    if (!identity && (prose.includes('\u2014') || prose.includes('\u2013'))) {
      violations.push(`${file}:${index + 1}: em/en dash in prose (use colon, comma, period or parentheses)`)
    }
    if (file.endsWith('.md')) {
      for (const [phrase, pattern] of STOCK) {
        if (pattern.test(prose)) {
          warnings.push(`${file}:${index + 1}: stock phrase "${phrase}"`)
          break
        }
      }
    }
  })
}

for (const line of violations) console.error(line)
for (const line of warnings) console.warn(line)

if (violations.length > 0) {
  console.error(`\n${violations.length} prose style violation(s). See docs/conventions/WRITING_STYLE.md`)
  process.exit(1)
}
console.log(`Prose style: clean (${warnings.length} stock-phrase warning(s))`)
